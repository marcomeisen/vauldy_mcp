#!/usr/bin/env python3
"""Tiny-font native-import output through actual protected MCP stdio.

Input stores are generated by OCRSmallTextMCPFixturesTests, never by editing
OCR JSON. The optional replay file contains only synthetic protected tool data;
it can test a chat model independently of a production relay or installation.
"""
import argparse
import hashlib
import json
from pathlib import Path
import tempfile
import time
import uuid

from smoke_test import Client, payload


FIELDS = ['Beitrag: 49,99 EUR', 'Beginn: 27.01.2026', 'Versicherungsart: Hausrat']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('binary', type=lambda value: Path(value).resolve())
    parser.add_argument('fixtures', type=lambda value: Path(value).resolve())
    parser.add_argument('--report', type=Path)
    parser.add_argument('--replay', type=Path)
    args = parser.parse_args()
    cases = json.loads((args.fixtures / 'wire-cases.json').read_text())
    assert {(case['size'], case['mode']) for case in cases} == {
        (str(size), mode) for size in [4, 5] for mode in ['v11', 'current']}
    report, replay = [], []
    with tempfile.TemporaryDirectory(prefix='vauldy-small-text-wire-') as temporary:
        root = Path(temporary)
        for index, case in enumerate(cases):
            vault = Path(case['vault'])
            # Refuse other stores: this command is only a generated fixture consumer.
            assert vault.resolve().is_relative_to(args.fixtures)
            before = vault.read_bytes()
            original_id = case['documentID']
            profile = root / f'profile-{index}.json'
            grant = dict(version=1, revision=str(uuid.uuid4()), connectionID=str(uuid.uuid4()),
                         connectionName='Synthetic tiny-text acceptance', enabled=True,
                         vaultPath=str(vault), allowedDocumentIDs=[original_id],
                         acknowledgedCloudDisclosure=True)
            profile.write_text(json.dumps(grant))
            profile_bytes = profile.read_bytes()
            client = Client(args.binary, profile)
            try:
                start = time.perf_counter()
                listed = payload(client.call('list_documents', includeExcerpts=False))
                assert listed['totalCount'] == 1 and listed['retrievalComplete']
                handle = listed['items'][0]['document']
                content = payload(client.call('read_document', document=handle))
                read_ms = (time.perf_counter() - start) * 1000
                assert content['containsEntireAvailableText'] and not content.get('nextCursor') and content['segments']
                assert all(segment['page'] == 1 and segment['source'] == f'[Quelle:{handle}:S.1]'
                           for segment in content['segments'])
                text = '\n'.join(segment['text'] for segment in content['segments'])
                found = [field for field in FIELDS if field in text]
                expected = 3 if case['mode'] == 'current' else (0 if case['size'] == '4' else 2)
                assert len(found) == expected, (case, found)
                assert text.count('Selbstbehalt: 110,00 EUR') == 1
                # OCR text and structured label support remain separate contracts.
                fields = payload(client.call('extract_document_fields', documents=[handle],
                                             fields=['cost', 'startDate', 'contractType']))
                rows = {row['field']: row for row in fields['results']}
                assert rows['cost']['status'] == ('evidenced' if expected else 'not-evidenced')
                if expected:
                    assert rows['cost']['evidence'][0]['value'] == '49,99 EUR'
                    assert rows['cost']['evidence'][0]['page'] == 1
                # "Beginn" and "Versicherungsart" are deliberately not silently
                # mapped to stricter contractual roles by this OCR change.
                assert rows['startDate']['status'] == 'not-evidenced'
                assert rows['contractType']['status'] == 'not-evidenced'
                topic = payload(client.call('list_documents', query='Hausrat', includeExcerpts=False))
                assert topic['totalCount'] == (1 if expected == 3 else 0)
                wire = json.dumps(content, ensure_ascii=False)
                assert all(value not in wire for value in
                           [str(vault.parent), original_id.lower(), original_id.upper(),
                            'geometry', 'sourceHash', 'textHash'])
                assert vault.read_bytes() == before and profile.read_bytes() == profile_bytes
                report.append(dict(size=int(case['size']), mode=case['mode'], exactFields=len(found),
                                   searchableByHausrat=topic['totalCount'] == 1,
                                   costStatus=rows['cost']['status'], startDateStatus=rows['startDate']['status'],
                                   contractTypeStatus=rows['contractType']['status'],
                                   selectionAndReadCalls=2, selectionAndReadMilliseconds=round(read_ms, 3),
                                   contentToolCalls=4, originalEvidencePreserved=True, page=1))
                replay.append(dict(case=f"{case['size']}pt-{case['mode']}", result=content))
                grant.update(enabled=False, revision=str(uuid.uuid4()))
                profile.write_text(json.dumps(grant))
                assert client.call('read_document', document=handle)['isError']
                assert client.call('extract_document_fields', documents=[handle])['isError']
                assert vault.read_bytes() == before
            finally:
                client.close()
    output = dict(passed=True, cases=report, revocationChecks=8,
                  actualChatModelTest=False, productionInstallationChanged=False,
                  binarySHA256=hashlib.sha256(args.binary.read_bytes()).hexdigest())
    if args.report:
        args.report.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n')
    if args.replay:
        prompt = ('Dies ist ein synthetischer OCR-Abnahmetest. Die folgenden vier unabhängigen '
                  'Datensätze sind tatsächlich lokal erzeugte, geschützte MCP-read_document-Antworten '
                  '(manueller Replay, kein Live-MCP-Aufruf in diesem Chat). Verwende ausschließlich '
                  'den Text jedes einzelnen Datensatzes. Übertrage keine Werte zwischen den Fällen. '
                  'Welche Versicherungsart, welcher Beitrag und welcher Beginn sind jeweils '
                  'belegt? Gib eine Tabelle mit Fall, Versicherungsart, Beitrag, Beginn und '
                  'Seitenbeleg aus. Nicht belegte Werte bleiben ausdrücklich offen. '
                  'Der Selbstbehalt ist kein Beitrag. Prüfe auch, ob die Angaben einen aktiven '
                  'Vertrag belegen; behaupte das nur bei einem ausdrücklichen Beleg. '
                  'Keine Plugins, keine Suche und keine anderen Dokumente verwenden.\n\n')
        args.replay.write_text(prompt + json.dumps(replay, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(output, ensure_ascii=False))


if __name__ == '__main__':
    main()
